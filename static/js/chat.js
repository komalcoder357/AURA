(function () {
  const A = (window.Aura = window.Aura || {});
  const box = A.$("#messages"), input = A.$("#input"), sendBtn = A.$("#sendBtn"), welcome = A.$("#welcome");
  const st = { conversationId: null, busy: false, abort: null };
  let typingEl = null;
  const ARROW = sendBtn.innerHTML;
  const STOP = '<svg viewBox="0 0 24 24" width="18" height="18" aria-hidden="true"><rect x="6" y="6" width="12" height="12" rx="2" fill="currentColor"/></svg>';

  const scrollDown = () => { box.scrollTop = box.scrollHeight; };
  const autosize = () => { input.style.height = "auto"; input.style.height = Math.min(input.scrollHeight, 160) + "px"; };
  function setBusy(b) {
    st.busy = b;
    sendBtn.innerHTML = b ? STOP : ARROW;
    sendBtn.setAttribute("aria-label", b ? "Stop generating" : "Send message");
  }
  const hideWelcome = () => { if (welcome.parentNode === box) box.removeChild(welcome); };

  function linkBtn(label, fn) {
    const b = document.createElement("button"); b.type = "button"; b.textContent = label; b.addEventListener("click", fn); return b;
  }
  function bubble(role, content, extra) {
    extra = extra || {};
    hideWelcome();
    const d = document.createElement("div");
    d.className = "msg " + role + (extra.error ? " error" : "");
    const body = document.createElement("div");
    body.className = "msg-body"; body.dir = "auto"; body.textContent = content;
    d.appendChild(body);
    if (role === "assistant" && !extra.error && !extra.streaming) decorate(d, content, extra);
    box.appendChild(d); scrollDown();
    return d;
  }
  // Source warnings, retry and read-aloud under an assistant message
  function decorate(d, content, extra) {
    const old = d.querySelector(".msg-meta"); if (old) old.remove();
    const meta = document.createElement("div"); meta.className = "msg-meta";
    const note = (t) => { const w = document.createElement("span"); w.className = "warn"; w.textContent = t; meta.appendChild(w); };
    if (extra.source === "fallback") note("Fallback message. Not generated by Gemini.");
    else if (extra.source === "safety_template") note("Safety message from a fixed template, not Gemini.");
    else if (extra.source === "partial") note("Interrupted response (partial).");
    if (extra.retryable) meta.appendChild(linkBtn("Retry", retry));
    meta.appendChild(linkBtn("Read aloud", () => speak(content)));
    if (extra.hint) { const h = document.createElement("span"); h.textContent = extra.hint; meta.appendChild(h); }
    d.appendChild(meta);
  }
  function hint(code) {
    if (!code) return "";
    if (code === "client_cancelled") return "";
    if (code === "sdk_not_installed") return "The google-genai package isn't installed. Run: pip install google-genai";
    if (code === "missing_api_key") return "GEMINI_API_KEY is not set. Add it to .env and restart the server.";
    if (/:(400|401|403)$/.test(code)) return "Gemini rejected the request. Check that your API key is valid.";
    if (/:404$/.test(code)) return "Gemini model not found. Check GEMINI_MODEL in .env.";
    if (/:429$/.test(code)) return "Gemini quota or rate limit reached. Wait and retry.";
    if (/Timeout|Connect|Network/i.test(code)) return "Could not reach Gemini. Check your internet connection.";
    return "Reason: " + code + ". See the server console for details.";
  }

  function showTyping() {
    hideWelcome();
    typingEl = document.createElement("div"); typingEl.className = "typing";
    const m = document.createElement("span"); m.setAttribute("data-mascot", ""); m.dataset.state = "processing";
    typingEl.appendChild(m); typingEl.appendChild(document.createTextNode("AURA is thinking…"));
    box.appendChild(typingEl); A.mascot.mount(m);
    A.mascot.set(A.$("#panelMascot"), "processing");
    scrollDown();
  }
  const hideTyping = () => { if (typingEl) { typingEl.remove(); typingEl = null; } };

  function speak(text) {
    const r = A.voice.speak(text, {
      onStart: () => A.mascot.set(A.$("#panelMascot"), "speaking"),
      onEnd: () => A.mascot.set(A.$("#panelMascot"), "idle"),
    });
    if (!r.ok) A.toast(r.reason);
  }

  /* One conversation turn, streamed. Used by the text composer and by voice mode.
     ui: { onDelta(text), onDone(done) }. Returns {meta, done}. Throws on network/HTTP errors. */
  async function runTurn(payload, ui, signal) {
    let meta = null, done = null;
    await A.streamChat(payload, {
      onMeta: (m) => {
        meta = m; st.conversationId = m.conversation.id;
        A.$("#chatTitle").textContent = m.conversation.title;
        if (!payload.regenerate) A.emotion.update(m.analysis, m.decision, m.distress);
        else A.emotion.update(m.analysis, m.decision, m.distress);
        if (m.memory_saved) A.toast("Saved to memory: " + m.memory_saved);
      },
      onDelta: (t) => { if (ui && ui.onDelta) ui.onDelta(t); },
      onDone: (d) => {
        done = d;
        A.emotion.setObservations(d.observations); A.emotion.setSpeed(d.timings_ms);
        if (d.error_type && d.error_type !== "client_cancelled") A.mascot.set(A.$("#panelMascot"), "error");
        A.app.refreshConversations();
        if (ui && ui.onDone) ui.onDone(d);
      },
    }, signal);
    return { meta, done };
  }

  async function turn(payload, userText) {
    setBusy(true);
    if (userText) bubble("user", userText);
    showTyping();
    st.abort = new AbortController();
    let el = null, text = "";
    try {
      await runTurn(payload, {
        onDelta: (t) => {
          if (!el) { hideTyping(); el = bubble("assistant", "", { streaming: true }); }
          text += t; el.firstChild.textContent = text; scrollDown();
        },
        onDone: (d) => {
          hideTyping();
          if (!el) el = bubble("assistant", d.assistant_message.content, { streaming: true });
          el.firstChild.textContent = d.assistant_message.content;
          decorate(el, d.assistant_message.content, { source: d.assistant_message.source, retryable: d.retryable, hint: hint(d.error_type) });
          if (A.settings && A.settings.data && A.settings.data.auto_speak && d.assistant_message.source === "gemini") speak(d.assistant_message.content);
        },
      }, st.abort.signal);
    } catch (e) {
      hideTyping();
      if (e.name === "AbortError") {
        if (el) decorate(el, text, { source: "partial", retryable: true });
      } else if (el && text) {
        decorate(el, text, { source: "partial", retryable: true, hint: e.message });
      } else {
        A.mascot.set(A.$("#panelMascot"), "error");
        bubble("assistant", "Couldn't get a reply: " + e.message, { error: true });
        if (userText) { input.value = userText; autosize(); }
      }
    } finally { st.abort = null; setBusy(false); input.focus(); }
  }

  function send() {
    if (st.busy) { if (st.abort) st.abort.abort(); return; }
    const text = input.value.trim();
    if (!text) return;
    input.value = ""; autosize();
    turn({ conversation_id: st.conversationId, message: text }, text);
  }
  function retry() {
    if (st.busy || !st.conversationId) return;
    const last = box.lastElementChild;
    if (last && last.classList.contains("assistant")) last.remove();
    turn({ conversation_id: st.conversationId, regenerate: true }, null);
  }

  function reset() {
    if (st.abort) st.abort.abort();
    st.conversationId = null; box.textContent = ""; box.appendChild(welcome);
    A.$("#chatTitle").textContent = "New chat"; input.value = ""; autosize(); A.emotion.reset();
  }
  async function load(id) {
    const r = await A.api("/api/conversations/" + encodeURIComponent(id));
    st.conversationId = r.conversation.id; box.textContent = "";
    A.$("#chatTitle").textContent = r.conversation.title;
    const last = r.messages.length - 1;
    r.messages.forEach((m, i) => bubble(m.role, m.content, { source: m.source, retryable: i === last && ["fallback", "partial", "safety_template"].indexOf(m.source) >= 0 && m.source !== "safety_template" }));
    A.emotion.reset(); A.emotion.setObservations(r.observations);
    if (r.analysis) A.emotion.update(r.analysis, r.decision, r.distress);
    scrollDown();
  }

  input.addEventListener("input", autosize);
  input.addEventListener("keydown", (e) => { if (e.key === "Enter" && !e.shiftKey && !e.isComposing) { e.preventDefault(); send(); } });
  sendBtn.addEventListener("click", send);
  A.chat = { state: st, reset, load, send, runTurn, speak };
})();
